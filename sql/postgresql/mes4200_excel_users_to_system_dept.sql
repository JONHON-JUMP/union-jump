WITH numbered AS (
  SELECT t.*, ROW_NUMBER() OVER (ORDER BY t.username) AS rn
  FROM tmp_mes4200_main_user t
  WHERE NOT EXISTS (
    SELECT 1 FROM system_users su
    WHERE LOWER(su.username) = LOWER(t.username) AND su.deleted = 0 AND su.tenant_id = 1
  )
),
ins AS (
  INSERT INTO system_users (
    id, user_uid, username, password, nickname, remark, dept_id, post_ids,
    email, mobile, sex, avatar, status,
    creator, create_time, updater, update_time, deleted, tenant_id
  )
  SELECT
    nextval('system_users_seq'),
    'U' || to_char(NOW(), 'YYYYMMDDHH24MISS') || lpad(n.rn::text, 3, '0'),
    n.username,
    '$2a$10$R7Aecpk2aXYfPZaIyTJXT.RQGYdn3PEIEU8cxge41vk/g1Lo1CQTW',
    n.nickname,
    COALESCE(n.remark, 'from MES4200 excel'),
    (SELECT dept_id FROM tmp_mes4200_dept_cfg LIMIT 1),
    '[]',
    '', '', n.sex, NULL, n.status,
    '1', NOW(), '1', NOW(), 0, 1
  FROM numbered n
  RETURNING id, username
)
SELECT COUNT(*) AS newly_created_system_users FROM ins;

