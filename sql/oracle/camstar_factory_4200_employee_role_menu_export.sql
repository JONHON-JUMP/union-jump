-- E1. 4200 角色
SELECT
    TRIM(ROLEID) AS role_id,
    ROLENAME     AS role_code,
    ROLETYPE,
    DESCRIPTION,
    NOTES,
    ISFROZEN
FROM ROLEDEF
WHERE ROLENAME LIKE '4200_%'
  AND ROLENAME NOT LIKE 'Default%'
ORDER BY ROLENAME;

-- E2. 角色-虚拟页权限（最核心的角色菜单关系）
SELECT
    rd.ROLENAME              AS role_code,
    SUBSTR(rd.ROLENAME, 1, INSTR(rd.ROLENAME, '_') - 1) AS workshop_code,
    rp.ROLEPERMISSIONNAME    AS vp_name,
    ui.UIVIRTUALPAGENAME,
    ui.SUBMENUNAME,
    ui.TEMPLATEPAGE
FROM ROLEPERMISSION rp
JOIN ROLEDEF rd ON rd.ROLEID = rp.ROLEID
LEFT JOIN UIVIRTUALPAGE ui ON ui.UIVIRTUALPAGENAME = rp.ROLEPERMISSIONNAME
WHERE rd.ROLENAME LIKE '4200_%'
  AND rd.ROLENAME NOT LIKE 'Default%'
ORDER BY rd.ROLENAME, rp.ROLEPERMISSIONNAME;

-- E3. 角色-菜单树（一级门户菜单 + 菜单项标题 + VP）
SELECT DISTINCT
    rd.ROLENAME                     AS role_code,
    SUBSTR(rd.ROLENAME, 1, INSTR(rd.ROLENAME, '_') - 1) AS workshop_code,
    pmf.PORTALMENUDEFINITIONNAME    AS portal_menu_name,
    pm.CAPTION                      AS menu_caption,
    pm.SEQUENCE                     AS menu_seq,
    rp.ROLEPERMISSIONNAME           AS vp_name
FROM UIVIRTUALPAGE ui
JOIN ROLEPERMISSION rp ON ui.UIVIRTUALPAGENAME = rp.ROLEPERMISSIONNAME
JOIN ROLEDEF rd ON rd.ROLEID = rp.ROLEID
JOIN PORTALMENUITEM pm ON pm.VIRTUALPAGEID = ui.UIVIRTUALPAGEID
JOIN PORTALMENUDEFINITION pmf ON pm.PARENTID = pmf.PORTALMENUDEFINITIONID
WHERE rd.ROLENAME LIKE '4200_%'
  AND rd.ROLENAME NOT LIKE 'Default%'
ORDER BY rd.ROLENAME, pmf.PORTALMENUDEFINITIONNAME, pm.SEQUENCE, pm.CAPTION;

-- E4. 4200 角色用到的一级菜单（去重）
SELECT DISTINCT pmf.PORTALMENUDEFINITIONNAME AS portal_menu_name
FROM UIVIRTUALPAGE ui
JOIN ROLEPERMISSION rp ON ui.UIVIRTUALPAGENAME = rp.ROLEPERMISSIONNAME
JOIN ROLEDEF rd ON rd.ROLEID = rp.ROLEID
JOIN PORTALMENUITEM pm ON pm.VIRTUALPAGEID = ui.UIVIRTUALPAGEID
JOIN PORTALMENUDEFINITION pmf ON pm.PARENTID = pmf.PORTALMENUDEFINITIONID
WHERE rd.ROLENAME LIKE '4200_%'
  AND rd.ROLENAME NOT LIKE 'Default%'
ORDER BY pmf.PORTALMENUDEFINITIONNAME;

