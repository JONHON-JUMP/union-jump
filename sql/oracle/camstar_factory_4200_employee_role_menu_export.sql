-- =============================================================================
-- Camstar MES：4200 车间人员 / 角色 / 菜单
--
-- 人员表 EMPLOYEE 没有 FACTORYID。现网新增人员 workshopCode 必填、teamCode 可选，
-- 所以「只走班组」会少人。正确口径是下面几条的并集去重：
--
--   1) 班组     TEAMEMPLOYEE → TEAM.FACTORYID
--   2) 会话车间 EMPLOYEE.SESSIONVALUESID → SESSIONVALUES.FACTORYID
--               （人员管理按车间查询走这条，没班组的人也在这里）
--   3) 默认产线 EMPLOYEE.PRODUCTLINEID → PRODUCTLINE.FACTORYID
--   4) 默认工位 EMPLOYEE.WORKCENTERID → WORKCENTER → PRODUCTLINE
--   5) 主组织   EMPLOYEE.PRIMARYORGANIZATIONID = 车间ID/组织ID
--
-- 4200 也不一定等于 FACTORY.FACTORYNAME，可能在 DEPT_WORKSHOP / 部门 OA_NO。
-- 先跑 A，确认解析出几个车间、各路径人数。
-- =============================================================================

-- 改这一处即可（Navicat / PLSQL 都能跑，不用 DEFINE）
-- =============================================================================
-- A. 解析 4200 对应哪些车间 + 各路径人数
-- =============================================================================
WITH p AS (
    SELECT '4200' AS workshop_code FROM dual
),
factory_hit AS (
    SELECT f.FACTORYID, f.FACTORYNAME, f.DESCRIPTION, f.DEPARTMENTID, f.ORGANIZATIONID, 'FACTORYNAME' AS hit
    FROM FACTORY f, p
    WHERE TRIM(f.FACTORYNAME) = p.workshop_code
       OR TRIM(f.FACTORYNAME) LIKE p.workshop_code || '%'
    UNION
    SELECT f.FACTORYID, f.FACTORYNAME, f.DESCRIPTION, f.DEPARTMENTID, f.ORGANIZATIONID, 'DEPT_WORKSHOP'
    FROM DEPT_WORKSHOP dw, p, FACTORY f
    WHERE TRIM(dw.WORKSHOP_CODE) = p.workshop_code
      AND (TRIM(f.FACTORYNAME) = TRIM(dw.WORKSHOP_CODE)
        OR TRIM(f.DEPARTMENTID) = TRIM(dw.DEPT_ID))
    UNION
    SELECT f.FACTORYID, f.FACTORYNAME, f.DESCRIPTION, f.DEPARTMENTID, f.ORGANIZATIONID, 'DEPT_OA'
    FROM DEPARTMENT d, p, FACTORY f
    WHERE (TRIM(d.OA_NO) = p.workshop_code OR TRIM(d.DEPARTMENTNAME) = p.workshop_code)
      AND f.DEPARTMENTID = d.DEPARTMENTID
    UNION
    -- IS_UNION_BY_DEPT=是：同部门其它车间也算进来
    SELECT f2.FACTORYID, f2.FACTORYNAME, f2.DESCRIPTION, f2.DEPARTMENTID, f2.ORGANIZATIONID, 'UNION_BY_DEPT'
    FROM DEPT_WORKSHOP dw, p, FACTORY f1, FACTORY f2
    WHERE TRIM(dw.WORKSHOP_CODE) = p.workshop_code
      AND NVL(dw.IS_UNION_BY_DEPT, '否') IN ('是', 'Y', '1', 'YES', 'yes')
      AND TRIM(f1.FACTORYNAME) = TRIM(dw.WORKSHOP_CODE)
      AND f2.DEPARTMENTID = f1.DEPARTMENTID
)
SELECT hit, TRIM(FACTORYID) AS factory_id, FACTORYNAME, DESCRIPTION
FROM factory_hit
ORDER BY hit, FACTORYNAME;


