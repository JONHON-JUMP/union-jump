--   ROLEDEF.ROLENAME 形如 4200_xxx
--     → ROLEPERMISSION (ROLEID + ROLEPERMISSIONNAME)
--     → UIVIRTUALPAGE.UIVIRTUALPAGENAME = ROLEPERMISSIONNAME
--     → PORTALMENUITEM.VIRTUALPAGEID
--     → PORTALMENUDEFINITION / 上级 PORTALMENUITEM
--
-- 车间过滤：ROLENAME LIKE '4200_%'
-- URL：Portal Studio 批量导出 all.xml 解析进 VP_URL_DESC 后才能拼上
